import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const web = fileURLToPath(new URL('../web/', import.meta.url));
const output = resolve(process.argv[2] || fileURLToPath(new URL('../build/generated/', import.meta.url)));
// Explicit allowlist excludes simulators, credentials and unrelated files.
const routes = [
  ['/', 'index.html', 'text/html; charset=utf-8'],
  ['/style.css', 'style.css', 'text/css; charset=utf-8'],
  ['/app.mjs', 'app.mjs', 'text/javascript; charset=utf-8'],
  ['/client.mjs', 'client.mjs', 'text/javascript; charset=utf-8'],
  ['/config.mjs', 'config.mjs', 'text/javascript; charset=utf-8'],
];
const files = await Promise.all(routes.map(async ([route, filename, mime]) => ({
  route, filename, mime, bytes: await readFile(join(web, filename)),
})));
const header = `// Generated by embed-web.mjs; do not edit.\n#pragma once
#include <cstddef>
namespace esp32fan { namespace web {
struct Asset {
    const char* path;
    const char* contentType;
    const unsigned char* data;
    std::size_t size;
};
extern const Asset assets[];
extern const std::size_t assetCount;
// Exact path match; nullptr for unknown paths. Data is not NUL-terminated.
const Asset* findAsset(const char* path);
} }
`;
const blocks = files.map(({ bytes }, index) => {
  const lines = [];
  for (let i = 0; i < bytes.length; i += 16) {
    lines.push('    ' + [...bytes.subarray(i, i + 16)].map((byte) => `0x${byte.toString(16).padStart(2, '0')}`).join(', '));
  }
  // Zero-sized C++ arrays are not standard; retain a sentinel but expose size 0.
  return `static const unsigned char data${index}[] = {\n${lines.join(',\n') || '    0x00'}\n};`;
});
const source = `// Generated by embed-web.mjs; do not edit.
#include "WebAssets.h"
#include <cstring>
namespace esp32fan { namespace web {
${blocks.join('\n')}
const Asset assets[] = {
${files.map((file, index) => `    {${JSON.stringify(file.route)}, ${JSON.stringify(file.mime)}, data${index}, ${file.bytes.length}}`).join(',\n')}
};
const std::size_t assetCount = sizeof(assets) / sizeof(assets[0]);
const Asset* findAsset(const char* path) {
    if (!path) return nullptr;
    for (std::size_t i = 0; i < assetCount; ++i) {
        if (std::strcmp(path, assets[i].path) == 0) return &assets[i];
    }
    return nullptr;
}
} }
`;
const manifest = files.map(({ route, filename, mime, bytes }) => ({
  route, filename, mime, size: bytes.length,
  sha256: createHash('sha256').update(bytes).digest('hex'),
}));
// Read every source first; a missing source fails before any output is written.
await mkdir(output, { recursive: true });
await writeFile(join(output, 'WebAssets.h'), header);
await writeFile(join(output, 'WebAssets.cpp'), source);
await writeFile(join(output, 'web-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(`Embedded ${files.length} routes, ${files.reduce((sum, file) => sum + file.bytes.length, 0)} bytes -> ${output}`);
